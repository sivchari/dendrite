func TestGenerate_outputStructure(t *testing.T) { //nolint:funlen // structure verification test
	t.Parallel()

	input := GenerateInput{
		Tool: config.Tool{
			Owner:         "cli",
			Repo:          "cli",
			Version:       "v2.87.0",
			Asset:         map[string]string{"darwin/arm64": "gh_{version}_macOS_arm64.tar.gz", "linux/amd64": "gh_{version}_linux_amd64.tar.gz"},
			Bins:          []string{"gh"},
			VersionPrefix: "v",
		},
		Locks: map[string]LockEntry{
			"darwin_arm64": {
				URL:    "https://github.com/cli/cli/releases/download/v2.87.0/gh_2.87.0_macOS_arm64.tar.gz",
				SHA256: "sha256-XXXX",
			},
		},
	}

	got, err := Generate(&input)
	if err != nil {
		t.Fatalf("unexpected error: %v", err)
	}

	output := string(got)

	// Verify the nix file starts with the function arguments block.
	if !strings.HasPrefix(output, "# Code generated by dendrite; DO NOT EDIT.\n{\n  stdenv,\n  fetchurl,\n}:\n") {
		t.Error("output does not start with expected function arguments block")
	}

	// Verify it contains stdenv.mkDerivation rec.
	if !strings.Contains(output, "stdenv.mkDerivation rec {") {
		t.Error("output does not contain stdenv.mkDerivation rec")
	}

	// Verify it contains the sources let binding.
	if !strings.Contains(output, "sources = {") {
		t.Error("output does not contain sources let binding")
	}

	// Verify it contains platform selection.
	if !strings.Contains(output, "platform = stdenv.hostPlatform.system;") {
		t.Error("output does not contain platform selection")
	}

	// Verify dontUnpack is present.
	if !strings.Contains(output, "dontUnpack = true;") {
		t.Error("output does not contain dontUnpack = true")
	}

	// Verify installPhase contains the expected commands.
	if !strings.Contains(output, "mkdir -p $out/bin") {
		t.Error("output does not contain mkdir -p $out/bin")
	}

	if !strings.Contains(output, "${platformSrc.extract}") {
		t.Error("output does not contain ${platformSrc.extract}")
	}

	// Verify the extract command is present in the sources.
	if !strings.Contains(output, "extract = ''tmpdir=$(mktemp -d) && tar -xzf $src -C $tmpdir && find $tmpdir -type f") {
		t.Error("output does not contain tar extract command in sources")
	}

	if !strings.Contains(output, "chmod +x $out/bin/gh") {
		t.Error("output does not contain chmod command for binary")
	}

	// Verify the file ends with a closing brace and newline.
	if !strings.HasSuffix(output, "}\n") {
		t.Error("output does not end with closing brace and newline")
	}
}

